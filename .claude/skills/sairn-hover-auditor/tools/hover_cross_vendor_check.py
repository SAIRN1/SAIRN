def main(argv):
    if '--selftest' in argv:
        return 0 if run_fixtures() else 1

    def opt(name, default=None):
        if name in argv:
            i = argv.index(name)
            if i + 1 < len(argv):
                return argv[i + 1]
        return default

    range_ = opt('--range')
    if not range_:
        print('usage: hover_cross_vendor_check.py --range <git-range> [--cwd DIR] '
              '[--own-verdict clean|N] [--key-path PATH] | --selftest')
        return 2
    cwd = opt('--cwd', os.getcwd())
    own_verdict = opt('--own-verdict')
    key_path = opt('--key-path', DEFAULT_KEY_PATH)

    try:
        result = run_check(range_, cwd, own_verdict=own_verdict, key_path=key_path)
    except CouldNotTell as e:
        print('COULD NOT RUN: %s' % e)
        return 2

    print('%d validated finding(s), %d dropped (hallucinated line/file), '
          'real_total_tokens=%d, agree=%r'
          % (len(result['valid_findings']), result['dropped_count'],
             result['real_total_tokens'], result['agree']))
    for f in result['valid_findings']:
        print('  - %s:%s -- %s -- %s' % (f['file'], f['line'], f['trigger'], f['description']))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
