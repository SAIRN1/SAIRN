# WHAT IT IS FOR: two finding records about the SAME item that overlap or
# disagree -- chat supplies both. The question is not "which is better
# written" but the narrower, checkable one: WHICH RECORD DOES A CONCRETE
# TRIGGER AND AN EXACT LINE IN THE DIFF ACTUALLY SUPPORT. Either, neither,
# or both is a real answer; "neither" is the one that matters most, because
# two confident records can both be unsupported by the diff in front of
# them, and a tiebreaker that must pick a winner would bury that.
#
# THIS MODE GETS THE DIFF, unlike the finding-review mode. That is the
# point of it: the adjudication is against real changed lines, not against
# which prose reads better. Still DIFF-ONLY -- no whole files.
#
# WHY NO IDENTITY IS GIVEN: the records are labelled A and B with no author,
# no seq and no severity, deliberately. If the reviewer knew one came from
# this role it could defer to it, which is the anchoring failure the
# independence-ordering rule in SKILL.md exists to prevent -- and here it
# would be self-serving rather than merely sloppy.
TIEBREAK_SYSTEM_PROMPT = (
    "You are adjudicating between two competing finding records about the "
    "same code change. You are shown the git diff and both records, "
    "labelled A and B, with no information about who wrote either. Decide "
    "which record -- if either -- is supported by a CONCRETE TRIGGER and an "
    "EXACT LINE that actually appears in this diff. Do not pick a winner on "
    "writing quality, confidence, detail or length. If a record's claim "
    "cannot be tied to a real changed line in this diff, it is not "
    "supported, however plausible it sounds. Answering 'neither' is a "
    "correct and expected outcome when neither record's claim is grounded "
    "in the diff, and 'both' is correct when both are independently "
    "grounded. You MUST quote the exact diff line you relied on, and cite "
    "its new-file line number from the @@ hunk headers. Always call the "
    "adjudicate_records tool."
)

TIEBREAK_TOOL = {
    'type': 'function',
    'function': {
        'name': 'adjudicate_records',
        'description': 'Record which competing finding record the diff actually supports.',
        'parameters': {
            'type': 'object',
            'properties': {
                'supported': {
                    'type': 'string',
                    'enum': ['A', 'B', 'both', 'neither'],
                    'description': "Which record the diff supports via a concrete trigger and an exact line.",
                },
                'confidence': {'type': 'string', 'enum': ['low', 'medium', 'high']},
                'cited_line_number': {
                    'type': 'integer',
                    'description': 'The exact new-file line number from the diff that your decision rests on. Use -1 if your answer is "neither" and no line applies.',
                },
                'quoted_diff_line': {
                    'type': 'string',
                    'description': 'The exact text of that diff line, copied verbatim. Empty string only if "neither".',
                },
                'trigger': {
                    'type': 'string',
                    'description': 'The concrete input or state that reaches the supported claim. Empty string only if "neither".',
                },
                'reasoning': {'type': 'string'},
            },
            'required': ['supported', 'confidence', 'cited_line_number',
                         'quoted_diff_line', 'trigger', 'reasoning'],
        },
    },
}


def build_tiebreak_payload(diff_text, record_a, record_b):
    """The exact text sent. Records are stripped to their claim text and
    labelled A/B -- no author, no seq, no severity, no vector. Assembled in
    one function so what crosses the boundary is auditable by reading it."""
    return '\n'.join([
        'GIT DIFF UNDER REVIEW:', diff_text, '',
        'RECORD A:', str(record_a).strip(), '',
        'RECORD B:', str(record_b).strip(), '',
        'Which record does a concrete trigger and an exact line in the diff '
        'above actually support? A, B, both, or neither.'])


def adjudicate_records(payload_text, api_key, http_post=None):
    """(verdict_dict, real_total_tokens). Same transport, caps, throttle
    and could-not-tell discipline as every other mode here."""
    body = json.dumps({
        'model': MODEL,
        'messages': [{'role': 'system', 'content': TIEBREAK_SYSTEM_PROMPT},
                     {'role': 'user', 'content': payload_text}],
        'tools': [TIEBREAK_TOOL],
        'tool_choice': {'type': 'function',
                         'function': {'name': 'adjudicate_records'}},
        'max_tokens': MAX_OUTPUT_TOKENS,
        'temperature': 0,
        'reasoning_effort': 'low',
    }).encode('utf-8')
    headers = {'Authorization': 'Bearer ' + api_key,
               'Content-Type': 'application/json',
               'User-Agent': 'sairn-hover-auditor/1.0'}
    if http_post is not None:
        status, data = http_post(GROQ_URL, headers, body)
    else:
        req = urllib.request.Request(GROQ_URL, data=body, headers=headers,
                                      method='POST')
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                status = resp.status
                data = json.loads(resp.read().decode('utf-8'))
        except urllib.error.HTTPError as e:
            raise CouldNotTell('Groq API HTTP %d: %s'
                                % (e.code, e.read().decode('utf-8', 'replace')[:300]))
        except Exception as e:
            raise CouldNotTell('Groq API call failed: %s: %s'
                                % (type(e).__name__, e))
    if status != 200:
        raise CouldNotTell('Groq API returned HTTP %d' % status)
    usage = data.get('usage') or {}
    toks = int(usage.get('total_tokens') or 0)
    try:
        message = data['choices'][0]['message']
    except (KeyError, IndexError, TypeError):
        raise CouldNotTell('Groq response had no choices[0].message')
    for call in (message.get('tool_calls') or []):
        fn = call.get('function') or {}
        if fn.get('name') == 'adjudicate_records':
            try:
                return json.loads(fn.get('arguments') or '{}'), toks
            except ValueError as e:
                raise CouldNotTell('adjudicate_records arguments did not parse: %s' % e)
    raise CouldNotTell('Groq did not return the forced adjudicate_records '
                        'tool call -- finish_reason=%r'
                        % data.get('choices', [{}])[0].get('finish_reason'))


def validate_tiebreak(verdict, added_lines):
    """(ok, reason). The same line-validation discipline the diff mode uses,
    applied to the tiebreaker's own citation: a decision for A or B must
    rest on a line that is REALLY in the diff. A 'neither' needs no line and
    is accepted without one -- that is the whole point of allowing it."""
    choice = (verdict or {}).get('supported')
    if choice not in ('A', 'B', 'both', 'neither'):
        return False, 'supported=%r is not one of A/B/both/neither' % choice
    if choice == 'neither':
        return True, 'neither -- no line citation required'
    line = verdict.get('cited_line_number')
    if not isinstance(line, int):
        return False, 'a decision for %r cites no integer line number' % choice
    real = set()
    for s in added_lines.values():
        real |= s
    if line not in real:
        return False, ('a decision for %r cites line %r, which is NOT an added '
                        'line anywhere in this diff -- the decision is dropped '
                        'rather than trusted' % (choice, line))
    return True, 'cited line %d is a real added line in the diff' % line


# ── PRE-FLIGHT CITATION CHECK, b69, built because the controls FAILED ────
# MEASURED, not anticipated. b69 added the two negative-control shapes the
# dispatch asked for and the evidence-only finding-review mode FAILED BOTH,
# plus a third shape found along the way:
#
#   * a line number BEYOND END OF FILE (cited :801 in a 321-line file)
#     -> AGREED, medium confidence.
#   * false CONTENT attributed to a real path and a real line, including a
#     fabricated quotation of an internal comment -> AGREED, HIGH.
#   * a FABRICATED PATH that does not exist in the repo at all -> AGREED,
#     HIGH, and it stated "The cited line directly shows the
#     implementation uses an in-memory plain object", claiming to have read
#     a line in a file that has never existed.
#
# That is not a reviewer being lenient, it is a reviewer with no way to
# check -- the mode gives it the finding's text and no repository, so every
# citation is unverifiable by construction and a confident fabrication
# reads exactly like a confident fact.
#
# THE FIX IS DETERMINISTIC AND LOCAL, NOT A BETTER PROMPT: verify every
# citation against the real repo BEFORE the call. Then the fabricated-path
# and beyond-EOF shapes cannot reach the vendor at all, and no amount of
# model credulity matters for them. This is the same discipline the diff
# mode already applies to the model's OWN citations, turned around to apply
# to the finding's citations on the way in -- and the same check
# hover_log.py's citation guard performs at write time, which refused this
# role's own b68 entry twice for exactly this class of imprecision.
#
# WHAT IT STILL CANNOT CATCH, stated rather than implied: false CONTENT at
# a real path and a real in-range line, where no quoted string is given to
# check against. That shape remains reachable and the mode's verdicts must
# not be read as evidence against it. Named in the output every run.
#
# ── b71: THE QUOTED-CONTENT HALF OF THAT GAP IS NOW CLOSED, and the
# remaining limit is narrower and stated precisely rather than inherited.
#
# The paragraph above was already scoped correctly -- "where no quoted
# string is given to check against" -- but nothing acted on the other
# branch. When a finding DOES bind a quoted fragment to a specific line,
# that fragment can be read off the real line and compared, and a
# fabricated quotation stops being a matter of vendor credulity. PF5
# asserted this gap as an honest limit for two batches; as of b71 it
# asserts the opposite for the bound case, and a NEW control (PF9) carries
# the genuinely remaining limit.
#
# WHICH SHAPES COUNT AS A BOUND QUOTATION, AND WHY NOT "EVERY BACKTICKED
# STRING". Measured against this role's own real log (1,617 entries) rather
# than chosen from taste:
#   * `frag` at path:line      -- 4 matches in 3 entries   ACCEPTED
#   * `frag` (:NNN)            -- 7 matches in 4 entries   ACCEPTED
#   * path:line ... `frag` within 80 chars -- 82 matches in 59 entries,
#     DELIBERATELY NOT ACCEPTED. That is the loose shape, and accepting it
#     would make every backticked identifier near a citation a claimed
#     quotation -- including tool names, header names and prose emphasis
#     that were never asserted to be ON the line. It would refuse dozens of
#     correct past entries. This is the same judgment the platform's own
#     tools/citation_anchor_rot_check.py makes in its ANCHOR_RE comment
#     ("NOT 'every backticked string', which would make every identifier in
#     a prose cell an anchor") -- convention reused, code not, because that
#     tool answers a different question (does an anchor resolve exactly once
#     anywhere in a markdown register cell's target) and because a hover
#     check must not depend on a file a build agent owns and can change
#     under it.
# So the check is OPT-IN BY SYNTAX: bind a fragment to a line and it gets
# verified; write prose near a citation and nothing is claimed or checked.
# The count of bound fragments is reported, so zero is visible as a not-run
# rather than passing as if content had been verified (PR SS1.11).
#
# WHAT A FAILURE DISTINGUISHES, because the two are not the same defect:
# DRIFT (the fragment is real and present in the file, just not at the
# cited line -- the code moved) vs FABRICATION (the fragment does not
# appear in the file at ANY line at `ref`). Both refuse; both name which
# one they are and, for drift, the real line number.

def _repo_root():
    return os.path.join(os.path.expanduser('~'), 'Documents', 'SAIRN-hover')


def _file_line_count(path, repo=None, ref='HEAD'):
    """(count_or_None, why). Reads the file from git at `ref` so the check
    is against a committed state rather than a dirty working tree."""
    repo = repo or _repo_root()
    r = subprocess.run(['git', 'show', '%s:%s' % (ref, path)], cwd=repo,
                        capture_output=True, text=True, encoding='utf-8',
                        errors='replace')
    if r.returncode != 0:
        return None, 'not present at %s in %s (%s)' % (
            ref, repo, (r.stderr or '').strip()[:80])
    return len(r.stdout.splitlines()), ''


_CITE_RE = re.compile(r'([A-Za-z0-9_./\\-]+\.(?:js|py|html|json|sql|md|jsonl|ts))\s*:\s*(\d+)')

_EXT = r'(?:js|py|html|json|sql|md|jsonl|ts)'

# The two BOUND-QUOTATION shapes, both requiring the fragment and the line
# number to be syntactically adjacent. See the long comment above for the
# third, loose shape that is measured and deliberately refused.
_QUOTE_AT_RE = re.compile(
    r'`([^`\n]{4,300})`\s+at\s+([A-Za-z0-9_./\\-]+\.%s)\s*:\s*(\d+)' % _EXT)
_QUOTE_PAREN_RE = re.compile(r'`([^`\n]{4,300})`\s*\(\s*:(\d+)\s*\)')


def _file_lines(path, repo=None, ref='HEAD'):
    """(lines_or_None, why). The file's real lines at `ref`, from git for
    the same reason _file_line_count reads from git: a dirty working tree
    would let an uncommitted edit satisfy a check about committed state."""
    repo = repo or _repo_root()
    r = subprocess.run(['git', 'show', '%s:%s' % (ref, path)], cwd=repo,
                        capture_output=True, text=True, encoding='utf-8',
                        errors='replace')
    if r.returncode != 0:
        return None, 'not present at %s in %s (%s)' % (
            ref, repo, (r.stderr or '').strip()[:80])
    return r.stdout.splitlines(), ''


def _norm_ws(s):
    """Collapse runs of whitespace to one space and strip. Applied to BOTH
    sides so a fragment quoted without its source indentation still
    matches. Case is NOT folded -- this compares code, where `Prefer` and
    `prefer` are different things."""
    return ' '.join(str(s).split())


def preflight_quoted_content(entry, repo=None, ref='HEAD'):
    """(problems, checked, notes) -- for every BOUND quotation in the
    entry, read the cited line from git at `ref` and require the quoted
    fragment to actually be there.

    `checked` counts bound fragments actually compared, so an entry that
    binds none reports zero rather than looking content-verified.
    `problems` entries name DRIFT vs FABRICATION explicitly."""
    problems = []
    notes = []
    checked = 0
    blob = ' '.join([str(entry.get('ref') or ''), str(entry.get('summary') or '')])

    # (fragment, path_or_None, line)
    bound = [(m.group(1), m.group(2).replace('\\', '/'), int(m.group(3)))
             for m in _QUOTE_AT_RE.finditer(blob)]
    paren = [(m.group(1), None, int(m.group(2)))
             for m in _QUOTE_PAREN_RE.finditer(blob)]

    # Path resolution for the `(:NNN)` shape, which names no file. The
    # candidate set is every path the entry itself already commits to.
    # FAIL CLOSED on ambiguity: a fragment bound to a line in an
    # unidentifiable file is refused, not waved through, because "I could
    # not tell which file" is not "the quotation checked out".
    candidates = set()
    shas = entry.get('source_shas')
    if isinstance(shas, dict):
        candidates |= {str(p).replace('\\', '/') for p in shas if p}
    for m in _CITE_RE.finditer(blob):
        candidates.add(m.group(1).replace('\\', '/'))
    if paren:
        if len(candidates) == 1:
            only = next(iter(candidates))
            paren = [(f, only, ln) for f, _, ln in paren]
        else:
            for frag, _, ln in paren:
                problems.append(
                    'quoted fragment is bound to (:%d) but the entry names %d '
                    'candidate path(s) %s, so which file the quotation is from '
                    'cannot be determined -- write it as `frag` at path:%d. '
                    'Fragment: %r'
                    % (ln, len(candidates), sorted(candidates) or '[none]',
                       ln, frag[:80]))
            paren = []

    cache = {}
    for frag, path, ln in bound + paren:
        if path not in cache:
            cache[path] = _file_lines(path, repo=repo, ref=ref)
        lines, why = cache[path]
        if lines is None:
            problems.append('quoted fragment cites a FILE that does not exist: '
                             '%s:%d -- %s' % (path, ln, why))
            continue
        if ln < 1 or ln > len(lines):
            problems.append('quoted fragment cites %s:%d but the file has %d '
                             'line(s) at %s' % (path, ln, len(lines), ref))
            continue
        checked += 1
        needle = _norm_ws(frag)
        if needle in _norm_ws(lines[ln - 1]):
            continue
        # A statement wrapped across lines is a real and legitimate way to
        # quote: accept the cited line joined with the two following it.
        span = _norm_ws(' '.join(lines[ln - 1:ln + 2]))
        if needle in span:
            notes.append('quoted fragment at %s:%d matches the cited line '
                          'joined with the 2 following -- a wrapped statement, '
                          'accepted' % (path, ln))
            continue
        hits = [i + 1 for i, l in enumerate(lines) if needle in _norm_ws(l)]
        if hits:
            # WEAK LOCALIZATION, DISCLOSED RATHER THAN SUPPRESSED. Measured
            # against 443 real past findings: the three DRIFT verdicts this
            # check produces are all on api/sd-data.js, and two of them
            # quote the 4-character fragment `read`, which occurs on five
            # lines. The verdict is still CORRECT -- the fragment is
            # genuinely not on the cited line -- but a fragment that occurs
            # many times localizes weakly, and a reader deserves to know
            # that before treating "the fragment is at 75, 87, 91, 102,
            # 110" as a precise relocation. The alternative, raising the
            # minimum fragment length until such cases vanish, would
            # silently stop checking short-but-real quotations; disclosure
            # keeps the check running and tells the truth about its
            # resolving power.
            weak = ('. NOTE: this fragment occurs on %d lines, so it '
                     'localizes WEAKLY -- the refusal is sound (it is not on '
                     'the cited line) but the suggested lines are not a '
                     'precise relocation' % len(hits)) if len(hits) > 3 else ''
            problems.append(
                'DRIFT -- quoted fragment is real but NOT at the cited line: '
                '%s:%d was cited, the fragment is at line(s) %s at %s. '
                'Fragment: %r%s'
                % (path, ln, ', '.join(str(h) for h in hits[:5]), ref,
                   frag[:80], weak))
        else:
            problems.append(
                'FABRICATION -- quoted fragment does not appear in %s at ANY '
                'line at %s, so this is not line drift: the content attributed '
                'to %s:%d was never there. Fragment: %r'
                % (path, ref, path, ln, frag[:80]))
    return problems, checked, notes


def preflight_citations(entry, repo=None, ref='HEAD', quoted=True,
                         notes_out=None):
    """(ok, problems, checked) -- verifies, against the real repository:
      * every path in source_shas exists at `ref`;
      * every `path:line` citation anywhere in ref/summary names a path
        that exists AND a line within that file's real line count;
      * b71 -- every BOUND quoted fragment is actually ON the line it is
        bound to, via preflight_quoted_content(). `quoted=False` turns only
        that third check off, so the b69 fixtures can still exercise the
        resolve-only behaviour they were written against.
    `problems` is a list of strings; `checked` counts what was actually
    verified, so a finding citing nothing reports zero rather than passing
    silently as if it had been checked."""
    problems = []
    checked = 0
    paths = set()
    shas = entry.get('source_shas')
    if isinstance(shas, dict):
        paths |= {str(p).replace('\\', '/') for p in shas if p}
    counts = {}

    for p in sorted(paths):
        n, why = _file_line_count(p, repo=repo, ref=ref)
        checked += 1
        if n is None:
            problems.append('cited FILE does not exist: %s -- %s' % (p, why))
        else:
            counts[p] = n

    blob = ' '.join([str(entry.get('ref') or ''), str(entry.get('summary') or '')])
    seen_pairs = set()
    for m in _CITE_RE.finditer(blob):
        p, ln = m.group(1).replace('\\', '/'), int(m.group(2))
        if (p, ln) in seen_pairs:
            continue
        seen_pairs.add((p, ln))
        if p not in counts:
            n, why = _file_line_count(p, repo=repo, ref=ref)
            checked += 1
            if n is None:
                problems.append('cited FILE does not exist: %s:%d -- %s'
                                 % (p, ln, why))
                continue
            counts[p] = n
        checked += 1
        if ln > counts[p]:
            problems.append('cited LINE is beyond end of file: %s:%d but the '
                             'file has %d line(s) at %s'
                             % (p, ln, counts[p], ref))
        elif ln < 1:
            problems.append('cited LINE is not a real line number: %s:%d' % (p, ln))

    # b71 -- THE CONTENT HALF. Runs after resolution so a fragment bound to
    # a file that does not exist is reported once by the stronger check
    # above rather than twice in different words.
    if quoted:
        q_problems, q_checked, q_notes = preflight_quoted_content(
            entry, repo=repo, ref=ref)
        problems.extend(q_problems)
        checked += q_checked
        # Notes are NOT problems (a wrapped statement is a legitimate
        # quotation) but they are not nothing either -- a caller that
        # passes a list gets them and prints them, so an accepted span is
        # visible rather than a silent widening of the comparison.
        if notes_out is not None:
            notes_out.extend(q_notes)
            notes_out.append('quoted fragments compared against their cited '
                             'line: %d' % q_checked)
    return (not problems), problems, checked


def load_finding(seq, log_path=LOG_PATH):
    """The real log entry for `seq`, or CouldNotTell. Reads the whole entry
    (unlike the transparency log, which deliberately narrows to seq/hash/ts)
    because the finding's own summary and citations ARE the evidence being
    reviewed here."""
    if not os.path.isfile(log_path):
        raise CouldNotTell('self-log not found at %s' % log_path)
    with open(log_path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            e = json.loads(line)
            if e.get('seq') == seq:
                if e.get('type') != 'finding':
                    raise CouldNotTell(
                        'seq=%d is type %r, not a finding -- this mode reviews '
                        'findings' % (seq, e.get('type')))
                return e
    raise CouldNotTell('no entry with seq=%d in %s' % (seq, log_path))


def build_finding_evidence(entry):
    """The exact text handed to the other vendor. Summary and citations
    only -- no source, no repo. Assembled in one place so what crosses the
    boundary is auditable by reading one function."""
    lines = ['FINDING seq=%s' % entry.get('seq'),
             'severity: %s' % (entry.get('severity') or '(unset)')]
    if entry.get('vector'):
        lines.append('severity vector: %s' % entry['vector'])
    lines.append('target (who owns the fix): %s' % (entry.get('target') or '-'))
    if entry.get('ref'):
        lines.append('cited evidence: %s' % entry['ref'])
    shas = entry.get('source_shas')
    if isinstance(shas, dict) and shas:
        # REAL SHAPE, found by this mode CRASHING on its first live run: the
        # values are {'sha': ..., 'source': ...} dicts, not bare sha
        # strings. The fixture had hand-built the bare-string shape and so
        # could never have caught it -- the exact "teleported-in fixture vs
        # the shape real data actually has" gap SKILL.md's own standing rule
        # 3 names. Both shapes are handled now and BOTH are fixture-locked.
        parts = []
        for p, v in sorted(shas.items()):
            if isinstance(v, dict):
                sha = str(v.get('sha') or '')
            else:
                sha = str(v or '')
            parts.append('%s -> %s' % (p, sha[:12]))
        lines.append('cited files (path -> blob sha at review time): %s'
                      % ', '.join(parts))
    lines.append('')
    lines.append('THE FINDING AS WRITTEN:')
    lines.append(entry.get('summary') or '(no summary)')
    return '\n'.join(lines)


