# ── token estimate, diff extraction, boilerplate stripping ─────────────────

def estimate_tokens(text):
    """~4 chars/token -- OpenAI/Groq's own published rule of thumb for
    English text and typical source code. A real tokenizer would be more
    exact; this is a disclosed heuristic, not a claim of precision, and it
    is used only to decide whether to even ATTEMPT a call, never to bill
    anything."""
    return max(1, (len(text) + 3) // 4)


def get_diff(range_, cwd):
    r = subprocess.run(['git', 'diff', range_], cwd=cwd, capture_output=True,
                        text=True, encoding='utf-8', errors='replace')
    if r.returncode != 0:
        raise CouldNotTell('git diff %s failed: %s' % (range_, r.stderr.strip()))
    if not r.stdout.strip():
        raise CouldNotTell('git diff %s produced no output -- empty range or '
                            'bad range syntax' % range_)
    return r.stdout


_BOILERPLATE_HEADER_RE = re.compile(
    r'^[+-](\s*(//|#|\*|/\*|SPDX-License-Identifier:).*'
    r'(license|copyright|generated by|all rights reserved).*)$',
    re.IGNORECASE)
_HUNK_RE = re.compile(r'^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@')


def strip_boilerplate(diff_text):
    """Three disclosed, bounded removals -- see module docstring. Pure,
    directly fixture-tested. Never removes an ordinary code comment that
    is not one of the three named shapes."""
    lines = diff_text.split('\n')
    out = []
    blank_run = 0
    for line in lines:
        content = line[1:] if line[:1] in ('+', '-', ' ') else line
        if _BOILERPLATE_HEADER_RE.match(line):
            continue
        if line[:1] in ('+', '-') and content.strip() == '':
            blank_run += 1
            if blank_run > 1:
                continue
        else:
            blank_run = 0
        out.append(line)
    return '\n'.join(out)


def added_lines_with_numbers(diff_text):
    """{filename: set(new_line_no for every real '+' line)} -- computed
    independently from the SAME diff text sent to the model, so a cited
    line can be checked against ground truth this tool derives itself,
    not trusted from the model's own claim."""
    result = {}
    current_file = None
    new_lineno = None
    for line in diff_text.split('\n'):
        if line.startswith('+++ '):
            path = line[4:].strip()
            if path.startswith('b/'):
                path = path[2:]
            current_file = path
            continue
        m = _HUNK_RE.match(line)
        if m:
            new_lineno = int(m.group(3))
            continue
        if new_lineno is None or current_file is None:
            continue
        if line.startswith('+') and not line.startswith('+++'):
            result.setdefault(current_file, set()).add(new_lineno)
            new_lineno += 1
        elif line.startswith('-') and not line.startswith('---'):
            pass  # removed line, does not consume a new-file line number
        elif line.startswith(' '):
            new_lineno += 1
    return result


# ── rate gate ────────────────────────────────────────────────────────────

class RateGate:
    """Persisted across invocations (this role's own process does not stay
    running between batches) in a small, gitignored JSON file. clock/sleep
    are injectable so the selftest never touches real time or the real
    state file."""

    def __init__(self, state_path=RATE_STATE_PATH, clock=time.time, sleeper=time.sleep):
        self.state_path = state_path
        self.clock = clock
        self.sleeper = sleeper

    def _load(self):
        try:
            with open(self.state_path, encoding='utf-8') as f:
                return json.load(f)
        except (OSError, ValueError):
            return []

    def _save(self, calls):
        try:
            with open(self.state_path, 'w', encoding='utf-8') as f:
                json.dump(calls, f)
        except OSError:
            pass  # best-effort persistence; a lost rate-state file makes
            # the NEXT call slightly more conservative, never less safe

    def check(self, estimated_tokens):
        """(ok, reason_or_None, wait_seconds). Does not mutate state --
        call record_call() only after a real call actually happens, so a
        refused attempt never consumes budget it did not use."""
        now = self.clock()
        calls = [c for c in self._load() if now - c.get('t', 0) < 60.0]
        if calls:
            since_last = now - max(c['t'] for c in calls)
            if since_last < MIN_INTERVAL_SECONDS:
                return False, ('RPM gate: only %.1fs since the last call, '
                                'need %.1fs (%d RPM cap)'
                                % (since_last, MIN_INTERVAL_SECONDS, RPM_LIMIT)), \
                       MIN_INTERVAL_SECONDS - since_last
        window_tokens = sum(c.get('tok', 0) for c in calls)
        if window_tokens + estimated_tokens + MAX_OUTPUT_TOKENS > TPM_BUDGET_CEILING:
            oldest = min((c['t'] for c in calls), default=now)
            return False, ('TPM gate: %d tokens already used in the trailing '
                            '60s + ~%d estimated for this call + %d capped '
                            'output would exceed the %d TPM ceiling'
                            % (window_tokens, estimated_tokens,
                               MAX_OUTPUT_TOKENS, TPM_BUDGET_CEILING)), \
                   max(0.0, 60.0 - (now - oldest))
        return True, None, 0.0

    def wait_or_refuse(self, estimated_tokens, max_wait=65.0):
        ok, reason, wait = self.check(estimated_tokens)
        if ok:
            return True, None
        if wait > max_wait:
            return False, (reason + (' (wait would exceed %ds cap -- refusing '
                                      'rather than hanging)' % int(max_wait)))
        self.sleeper(wait)
        ok2, reason2, _ = self.check(estimated_tokens)
        if not ok2:
            return False, reason2 + ' (still blocked after waiting)'
        return True, None

    def record_call(self, real_total_tokens):
        calls = self._load()
        now = self.clock()
        calls = [c for c in calls if now - c.get('t', 0) < 60.0]
        calls.append({'t': now, 'tok': real_total_tokens})
        self._save(calls)


# ── the schema and the call ─────────────────────────────────────────────

REPORT_FINDINGS_TOOL = {
    'type': 'function',
    'function': {
        'name': 'report_findings',
        'description': 'Report real defects found in this diff, each with a concrete trigger and the exact line it occurs on. Empty list if genuinely clean.',
        'parameters': {
            'type': 'object',
            'properties': {
                'findings': {
                    'type': 'array',
                    'items': {
                        'type': 'object',
                        'properties': {
                            'file': {'type': 'string'},
                            'line': {'type': 'integer', 'description': 'The exact new-file line number this finding is on, as shown in the diff.'},
                            'trigger': {'type': 'string', 'description': 'The specific input or state that reaches this defect.'},
                            'description': {'type': 'string'},
                        },
                        'required': ['file', 'line', 'trigger', 'description'],
                    },
                },
            },
            'required': ['findings'],
        },
    },
}

SYSTEM_PROMPT = (
    "You are an independent code reviewer seeing ONLY a git diff, no other "
    "file context. Report real defects the diff itself introduces. Every "
    "finding MUST cite the exact new-file line number shown in the diff's "
    "own @@ hunk headers, and MUST name the concrete trigger -- the "
    "specific input or state that reaches it. Do not invent line numbers; "
    "if you cannot point to a real line in this diff, do not report it. "
    "Call report_findings even if the diff is clean (with an empty list)."
)


def ask_groq(diff_text, api_key, http_post=None):
    """http_post(url, headers, body_bytes) -> (status, response_dict) is
    injectable for the selftest. Returns (findings_list, real_total_tokens).
    Raises CouldNotTell on any failure -- auth, rate limit, network, or a
    response with no forced tool call."""
    body = json.dumps({
        'model': MODEL,
        'messages': [{'role': 'system', 'content': SYSTEM_PROMPT},
                     {'role': 'user', 'content': diff_text}],
        'tools': [REPORT_FINDINGS_TOOL],
        'tool_choice': {'type': 'function', 'function': {'name': 'report_findings'}},
        'max_tokens': MAX_OUTPUT_TOKENS,
        'temperature': 0,
        # gpt-oss is a reasoning model: found live, first real end-to-end
        # drive against a real ~5000-token diff -- at default reasoning
        # effort it spent the entire MAX_OUTPUT_TOKENS budget on internal
        # reasoning and never reached the forced tool call at all (a real
        # HTTP 400 tool_use_failed, not a timeout or auth error). 'low'
        # leaves enough of the capped budget for the actual tool call.
        'reasoning_effort': 'low',
    }).encode('utf-8')
    headers = {'Authorization': 'Bearer ' + api_key,
               'Content-Type': 'application/json',
               'User-Agent': 'sairn-hover-auditor/1.0'}

    if http_post is not None:
        status, data = http_post(GROQ_URL, headers, body)
    else:
        req = urllib.request.Request(GROQ_URL, data=body, headers=headers, method='POST')
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                status = resp.status
                data = json.loads(resp.read().decode('utf-8'))
        except urllib.error.HTTPError as e:
            raise CouldNotTell('Groq API HTTP %d: %s' % (e.code, e.read().decode('utf-8', 'replace')[:300]))
        except Exception as e:
            raise CouldNotTell('Groq API call failed: %s: %s' % (type(e).__name__, e))

    if status != 200:
        raise CouldNotTell('Groq API returned HTTP %d' % status)

    usage = data.get('usage') or {}
    real_total_tokens = int(usage.get('total_tokens') or 0)

    try:
        message = data['choices'][0]['message']
    except (KeyError, IndexError, TypeError):
        raise CouldNotTell('Groq response had no choices[0].message')

    for call in (message.get('tool_calls') or []):
        fn = call.get('function') or {}
        if fn.get('name') == 'report_findings':
            try:
                args = json.loads(fn.get('arguments') or '{}')
            except ValueError as e:
                raise CouldNotTell('report_findings arguments did not parse as JSON: %s' % e)
            return args.get('findings') or [], real_total_tokens

    raise CouldNotTell('Groq did not return the forced report_findings tool call '
                        '-- finish_reason=%r' % data.get('choices', [{}])[0].get('finish_reason'))


def validate_findings(findings, added_lines):
    """(valid, dropped_count, dropped_reasons) -- a finding citing a
    (file, line) that is not a real '+' line in the diff this tool itself
    parsed is dropped, counted, and the reason kept, never silently kept
    as-is and never silently discarded with no trace."""
    valid = []
    dropped = []
    for f in findings:
        file_ = f.get('file')
        line = f.get('line')
        real_lines = added_lines.get(file_) or added_lines.get(os.path.basename(file_ or ''), set())
        if not isinstance(line, int) or line not in real_lines:
            dropped.append('%s:%s is not a real added line in this diff' % (file_, line))
            continue
        valid.append(f)
    return valid, len(dropped), dropped


# ── logging ─────────────────────────────────────────────────────────────

def log_result(range_, valid_findings, dropped_count, own_verdict, log_path_override=None):
    groq_clean = len(valid_findings) == 0
    agree = None
    if own_verdict is not None:
        own_clean = (own_verdict == 'clean')
        agree = (groq_clean == own_clean)

    lines = ['CROSS-VENDOR CHECK (Groq/%s, independent of this role and of '
             'H2) on range %s: %d validated finding(s)%s.'
             % (MODEL, range_, len(valid_findings),
                ' (+%d dropped: cited a line not actually in this diff)' % dropped_count
                if dropped_count else '')]
    for f in valid_findings:
        lines.append('  - %s:%s -- trigger: %s -- %s'
                      % (f.get('file'), f.get('line'), f.get('trigger'), f.get('description')))
    if own_verdict is not None:
        lines.append('')
        lines.append('Compared against this role\'s own verdict on the same range (%s): %s'
                      % (own_verdict, 'AGREES' if agree else 'DISAGREES'))
        if not agree:
            lines.append('DISAGREEMENT -- flagged, not silently discarded.')

    summary = '\n'.join(lines)
    etype = 'finding' if (agree is False or (agree is None and valid_findings)) else 'check'
    hover_log_script = _hover_log_script_path()
    if hover_log_script is None:
        return 2, '', ('COULD NOT RUN: no hover_log.py found at %s or the '
                        'tracked platform copy -- nothing logged.' % HERE), agree
    argv = [sys.executable, hover_log_script, '--add',
            '--type', etype, '--target', 'self', '--ref', 'range=%s' % range_,
            '--summary', summary]
    if etype == 'finding':
        argv += ['--severity', 'moderate']
    env = dict(os.environ)
    if log_path_override:
        env['HOVER_LOG_PATH_OVERRIDE'] = log_path_override
    r = subprocess.run(argv, cwd=HERE, capture_output=True, text=True,
                        encoding='utf-8', env=env)
    return r.returncode, r.stdout, r.stderr, agree


# ── orchestration ───────────────────────────────────────────────────────

def run_check(range_, cwd, own_verdict=None, key_path=DEFAULT_KEY_PATH, gate=None):
    gate = gate or RateGate()
    diff_text = get_diff(range_, cwd)
    stripped = strip_boilerplate(diff_text)
    added = added_lines_with_numbers(stripped)

    prompt_tokens_est = estimate_tokens(SYSTEM_PROMPT) + estimate_tokens(stripped)
    if prompt_tokens_est + MAX_OUTPUT_TOKENS + TOKEN_SAFETY_MARGIN > TPM_BUDGET_CEILING:
        raise CouldNotTell('estimated %d prompt tokens + %d capped output + %d '
                            'safety margin exceeds the %d TPM ceiling on its own, '
                            'before any rate-window accounting -- range too large '
                            'for a single diff-only call'
                            % (prompt_tokens_est, MAX_OUTPUT_TOKENS,
                               TOKEN_SAFETY_MARGIN, TPM_BUDGET_CEILING))

    ok, reason = gate.wait_or_refuse(prompt_tokens_est)
    if not ok:
        raise CouldNotTell('rate-limited: %s' % reason)

    if not os.path.isfile(key_path):
        raise CouldNotTell('no Groq key at %s' % key_path)
    with open(key_path, encoding='utf-8') as f:
        api_key = f.read().strip()

    findings, real_total_tokens = ask_groq(stripped, api_key)
    gate.record_call(real_total_tokens)
    valid, dropped_count, dropped_reasons = validate_findings(findings, added)
    rc, out, err, agree = log_result(range_, valid, dropped_count, own_verdict)
    return {'valid_findings': valid, 'dropped_count': dropped_count,
            'dropped_reasons': dropped_reasons, 'real_total_tokens': real_total_tokens,
            'agree': agree, 'log_rc': rc}


