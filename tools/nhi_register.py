"""nhi_register.py -- every NON-HUMAN IDENTITY, its OWNER and its SCOPE.

    python tools/nhi_register.py            # write docs/NHI-REGISTER.md
    python tools/nhi_register.py --check    # is the document still true?
    python tools/nhi_register.py --selftest

── WHY THIS IS NOT docs/SECRETS-INVENTORY.md ────────────────────────────────
That document is generated by `tools/secrets_inventory.py`, which finds
credentials by scanning code for `process.env.X` reads. It is the right tool for
what it does and this file does not replace it -- it CITES it.

**AN ENV-VAR SCAN CANNOT ANSWER "WHO OWNS EVERY LIVE CREDENTIAL", AND THE REASON
IS STRUCTURAL RATHER THAN A GAP IN ITS COVERAGE.** Three of the four identity
classes on this platform are not environment variables at all:

  * the **GitHub PAT** -- held by a human and by CI, never read from
    `process.env` anywhere in this repo;
  * **`sairn_backup_reader`** -- a Postgres LOGIN role created by
    `sql/backup_reader_role.sql`. The role is the identity; the password is a
    property of it;
  * **each clone's push access** -- four working copies with write rights to
    `origin/main`, credentialed by the Windows credential manager.

So the register is keyed on IDENTITY, not on variable name, and an env-var
credential appears here as *a credential belonging to an identity* rather than
as a row of its own.

── WHAT MAKES IT A CHECK RATHER THAN A LIST ─────────────────────────────────
A written list of owners goes stale the first time somebody adds a credential,
and nothing announces the day it stopped being complete. Two things are therefore
DERIVED from the repo on every run and diffed against the hand-written half:

  1. every `CREDENTIAL` in `secrets_inventory.SECRETS` must be attributed to an
     identity here. A new secret classified as a credential and not attributed
     makes this tool REFUSE, the same way a new tool with no `PURPOSES` entry
     makes `tooling_inventory.py` refuse;
  2. every Postgres role this repo CREATES (`create role <name>` in `sql/`) must
     appear here. Minting a login role is exactly the act most likely to happen
     without anybody recording who owns it.

`--check` answers whether the published document still matches. The hand-written
half is OWNER and SCOPE, because neither is derivable -- ownership is a decision.

── THE HONEST LIMITS, STATED HERE RATHER THAN DISCOVERED ────────────────────
  * **It cannot see an identity that exists only in a console.** A Vercel token,
    a Supabase personal access token, or a GitHub Action's OIDC identity minted
    in a web UI leaves no trace in this repo. Those are recorded here by HAND on
    somebody's word, and rows sourced that way are marked `attested`.
  * **It does not verify a credential is still live**, has been rotated, or has
    the scope claimed for it. No clone holds any of them. `last_rotated` is
    attested, never measured, and a blank means NOBODY KNOWS rather than never.
  * **It does not check least privilege.** `tools/role_gate_invariants.js` and
    the grant-sweep work own that question.
"""
