def env_credentials():
    """Every CREDENTIAL-kind variable secrets_inventory already classifies."""
    try:
        import secrets_inventory
    except Exception as e:                                   # noqa: BLE001
        raise CouldNotTell('could not import secrets_inventory: %r' % e)
    secrets = getattr(secrets_inventory, 'SECRETS', None)
    if not isinstance(secrets, dict) or not secrets:
        raise CouldNotTell('secrets_inventory.SECRETS is missing or empty')
    return sorted(k for k, v in secrets.items()
                  if isinstance(v, (list, tuple)) and v and v[0] == 'CREDENTIAL')


def created_roles():
    """Every Postgres role this repo CREATES. Minting a login role is the act
    most likely to happen with nobody recording who owns it."""
    ls = subprocess.run(['git', '-C', REPO, 'ls-files', 'sql/*.sql'],
                        capture_output=True, encoding='utf-8', errors='replace')
    if ls.returncode != 0:
        raise CouldNotTell('git ls-files failed, so no SQL file was read')
    found = set()
    pat = re.compile(r'create\s+role\s+([A-Za-z_][\w]*)', re.I)
    for rel in [f for f in ls.stdout.split('\n') if f]:
        try:
            txt = io.open(os.path.join(REPO, rel), encoding='utf-8',
                          errors='replace').read()
        except OSError:
            continue
        for m in pat.finditer(txt):
            found.add(m.group(1).lower())
    return sorted(found)


def gaps():
    """(unattributed_credentials, unregistered_roles). Either one refuses."""
    declared = declared_credentials()
    unattributed = [c for c in env_credentials() if c not in declared]
    ids = set(i['id'].lower() for i in IDENTITIES)
    unregistered = [r for r in created_roles() if r not in ids]
    return unattributed, unregistered


