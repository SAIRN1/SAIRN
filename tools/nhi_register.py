def _selftest():
    ok = True

    def check(name, cond, detail=''):
        nonlocal ok
        print(('  ok   ' if cond else '  FAIL ') + name + ('' if cond else '  ' + str(detail)))
        if not cond:
            ok = False

    print('1. the refusal fires in both directions')
    saved = list(IDENTITIES)
    try:
        # Drop the identity owning ANTHROPIC_API_KEY and the register must refuse.
        IDENTITIES[:] = [i for i in saved if i['id'] != 'anthropic-api']
        try:
            render()
            check('an unattributed CREDENTIAL refuses', False, 'it rendered')
        except CouldNotTell as e:
            check('an unattributed CREDENTIAL refuses', 'ANTHROPIC_API_KEY' in str(e))
        # Drop the backup reader and the created-role check must refuse.
        IDENTITIES[:] = [i for i in saved if i['id'] != 'sairn_backup_reader']
        try:
            render()
            check('a `create role` with no entry refuses', False, 'it rendered')
        except CouldNotTell as e:
            check('a `create role` with no entry refuses',
                  'sairn_backup_reader' in str(e))
    finally:
        IDENTITIES[:] = saved

    print('\n2. CONTROL: the real register renders')
    try:
        body = render()
        check('it renders with the real IDENTITIES', 'identity | kind | owner' in body)
        check('...and every identity appears',
              all(i['id'] in body for i in IDENTITIES))
    except CouldNotTell as e:
        check('it renders with the real IDENTITIES', False, e)

    print('\n3. the derived halves really read the repo')
    try:
        check('secrets_inventory yields CREDENTIALs', len(env_credentials()) >= 10,
              len(env_credentials()))
        check('sql/ yields at least the backup reader',
              'sairn_backup_reader' in created_roles(), created_roles())
    except CouldNotTell as e:
        check('the derived halves read', False, e)

    # ── 3b. THE CLONE COUNT IS MEASURED, AND THE MEASUREMENT IS DRIVEN ──────
    # Added 2026-09-17 with the derivation itself. An arm that only asserted
    # "clone_scope() returns a string" would pass on a function that had
    # silently reverted to a hardcoded list, which is the exact failure this
    # replaced -- so the arms below check that it FINDS THIS CLONE, that it
    # finds MORE THAN THE FOUR the old row named, and that it REFUSES rather
    # than guessing when it cannot read.
    print('\n3b. the clone population is counted from disk and fails closed')
    try:
        names = sibling_clones()
        me = os.path.basename(REPO)
        check('the enumeration finds THIS clone -- if it cannot find the one it '
              'is running in, nothing it says about the others is worth reading',
              me in names, (me, names))
        check('it finds the FIFTH clone the typed list was missing',
              len(names) >= 5, names)
        body_scope = clone_scope()
        check('...and the published scope names the count it actually measured',
              str(len(names)) + ' working copies' in body_scope, body_scope[:80])
        check('the old hardcoded four is not in the output',
              'FOUR working copies' not in body_scope)
    except CouldNotTell as e:
        check('the clone enumeration ran', False, e)

    # THE FAIL-CLOSED HALF, DRIVEN. A check that depends on another tool must
    # fail CLOSED when that tool is absent (PR 1.11), and the only way to know
    # this one does is to take the tool away.
    try:
        real = globals()['REPO']
        globals()['REPO'] = os.path.join(real, '__no_such_clone__')
        raised = False
        try:
            sibling_clones()
        except CouldNotTell:
            raised = True
        except Exception:
            raised = False
        check('with an unreadable repo root it RAISES rather than returning a '
              'list -- a quiet revert to the typed four is the defect itself',
              raised)
    finally:
        globals()['REPO'] = real

    print('\n4. a blank rotation date is NOT rendered as "never"')
    try:
        body = render()
        check('no row claims a rotation nobody attested',
              'never rotated' not in body.lower())
        check('...and the document says a blank means NOBODY KNOWS',
              'NOBODY KNOWS, not never' in body)
    except CouldNotTell as e:
        # Guarded, because the first version called render() bare here and the
        # selftest CRASHED instead of reporting when the real register was
        # incomplete -- a selftest that dies on a real finding is a selftest
        # nobody can use to fix the finding.
        check('no row claims a rotation nobody attested', False, e)

    print('')
    print('  all arms pass' if ok else '  ARMS FAILED')
    return 0 if ok else 2


