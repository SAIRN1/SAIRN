-- sql/provisioning_gap_check_2026-08-25.sql
-- READ-ONLY. Closes two open rows in docs/SAIRN-OPEN-WORK-INDEX.md in one pass:
--   * the 41 declared tables no API path can reach, and
--   * the 36 session-gated resources the read-probe sweep could not measure.
--
-- Run as the owner in the Supabase SQL editor. Nothing here writes, creates,
-- drops or grants -- it is three SELECTs against catalog views.
--
-- WHY THIS EXISTS. api/sd-data.js reports `provisioned:false` when a table is
-- missing, so a read probe answers the provisioning question for any table
-- reachable as a registered resource. 150 of 186 were confirmed live that way
-- on 2026-08-25 with zero unprovisioned. The remaining gap is structural, not
-- effort: 36 resources require an employee session token a licence key cannot
-- produce (all of SAIRNcare, SAIRNroofing, SAIRNsenior, SAIRNbuild), and 41
-- declared tables have no registered resource at all. Both are invisible to
-- any client-side method. This query is the only thing that closes them.
--
-- THE 224 BELOW ARE DERIVED, NOT HAND-TYPED. Extracted from every
-- `create table` in sql/*.sql with SQL comments stripped by a quote-aware
-- state machine, then the two transient sweep baselines removed. The naive
-- version of that grep counted `create table` inside COMMENTS and invented
-- five phantom tables (alone, anywhere, for, if, to) out of prose in file
-- headers -- which is exactly how a 231 was reported before Cody's 224 was
-- confirmed correct. If this list is ever regenerated, strip comments first.

