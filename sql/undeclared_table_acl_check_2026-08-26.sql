-- sql/undeclared_table_acl_check_2026-08-26.sql
-- READ-ONLY. Four SELECTs, independent, no shared state. Nothing here writes,
-- creates, drops, grants, revokes or alters.
--
-- ── THE QUESTION ──────────────────────────────────────────────────────────
-- `business_profiles`, `ai_memories` and `employees` were found on 2026-08-25
-- to be live with no schema file, and all three carried anon/authenticated
-- TRUNCATE/REFERENCES/TRIGGER -- the Supabase default-ACL baseline that
-- sql/append_only_grant_audit.sql and the 2026-08-24 TRUNCATE sweep removed
-- everywhere else. They were never in scope for either run for one reason: a
-- privilege sweep driven off sql/ inherits sql/'s omissions. It cannot revoke
-- on a table it has never heard of.
--
-- That is a mechanism, not a coincidence, so it should apply to EVERY
-- live-but-not-declared table -- 25 of them when the gap check ran on
-- 2026-08-25, 22 now that those three are declared. This file confirms that
-- rather than assuming it. The prediction is written down before the answer
-- comes back, on purpose: if the other 22 come back CLEAN, the reasoning above
-- is wrong and that is worth knowing more than being right was.
--
-- Section 2 is the answer. Sections 1 and 3 are controls, section 4 is scope.
--
-- The 227 names below are generated from every `create table` in sql/*.sql
-- with comments stripped by a quote-aware state machine, minus two transient
-- sweep baselines. 224 before the three new schema files, 227 after. Do NOT
-- hand-edit this list -- regenerate it. The naive version of the same
-- extraction counts `create table` inside COMMENTS and invents phantom tables
-- named `alone`, `anywhere`, `for`, `if` and `to` out of prose in file
-- headers, which is how a 231 got reported once already.

-- ── 1. CONTROL: the three tables just declared and revoked ─────────────────
-- Run this FIRST. Expect service_role -> INSERT, SELECT, UPDATE on each, and
-- NO anon or authenticated rows at all. If anon/authenticated still appear,
-- the revoke line in those migrations did not run and section 2 is measuring a
-- world that did not change. If service_role is missing or short a verb, the
-- `revoke all` ran and the re-grant did not -- stop and fix that first, it
-- breaks the live app.
select table_name,
       grantee,
       string_agg(privilege_type, ', ' order by privilege_type) as privileges
  from information_schema.role_table_grants
 where table_schema = 'public'
   and table_name in ('business_profiles', 'ai_memories', 'employees')
   and grantee in ('service_role', 'anon', 'authenticated')
 group by table_name, grantee
 order by table_name, grantee;

