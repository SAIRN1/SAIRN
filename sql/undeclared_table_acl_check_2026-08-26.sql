select t.table_name,
       g.grantee,
       string_agg(g.privilege_type, ', ' order by g.privilege_type) as privileges
  from information_schema.tables t
  left join declared d on d.table_name = t.table_name
  join information_schema.role_table_grants g
    on g.table_schema = t.table_schema
   and g.table_name   = t.table_name
 where t.table_schema = 'public'
   and t.table_type   = 'BASE TABLE'
   and d.table_name is null              -- live, declared nowhere
   and g.grantee in ('anon', 'authenticated')
 group by t.table_name, g.grantee
 order by t.table_name, g.grantee;

